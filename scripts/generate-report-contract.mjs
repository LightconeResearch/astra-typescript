// Development-only: vendor a pinned Git revision, or generate/check its browser-safe contract.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = resolve(root, "vendor/astra-tools");
const sourcePath = resolve(vendor, "source.json");
const source = JSON.parse(readFileSync(sourcePath, "utf8"));
const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === "--check";
const sync = args.length === 2 && args[0] === "--sync";
if (args.length && !check && !sync) throw new Error("Use no arguments, --check, or --sync <repository>.");
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const write = (path, content) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
};

if (sync) {
  const git = (...options) => execFileSync("git", ["-C", args[1], ...options]);
  const files = git("ls-tree", "-r", "--name-only", source.revision, "--", "LICENSE",
    "src/astra/model/reports.schema.json", "tests/report-fixtures").toString("utf8").trim().split("\n");
  source.files = {};
  for (const path of files) {
    const local = path === "src/astra/model/reports.schema.json" ? "reports.schema.json" : path.replace(/^tests\//, "");
    const bytes = git("show", `${source.revision}:${path}`);
    write(resolve(vendor, local), bytes);
    source.files[local] = { path, sha256: digest(bytes) };
  }
  write(sourcePath, `${JSON.stringify(source, null, 2)}\n`);
}
for (const [local, expected] of Object.entries(source.files)) {
  if (digest(readFileSync(resolve(vendor, local))) !== expected.sha256) {
    throw new Error(`Vendored artifact changed: ${local}. Sync the pinned revision intentionally.`);
  }
}
const schema = JSON.parse(readFileSync(resolve(vendor, "reports.schema.json"), "utf8"));
const definitions = schema.$defs;
const reports = [
  ["ResolvedAnalysis", "RESOLVED_ANALYSIS_SCHEMA_VERSION"],
  ["ValidationReport", "VALIDATION_REPORT_SCHEMA_VERSION"],
  ["StatusReport", "STATUS_REPORT_SCHEMA_VERSION"],
];
const only = (node, keys) => {
  for (const key of Object.keys(node)) {
    if (!keys.includes(key)) throw new Error(`Unsupported report schema keyword: ${key}`);
  }
};
only(schema, ["$schema", "$id", "title", "$comment", "oneOf", "$defs"]);
if (schema.$schema !== "https://json-schema.org/draft/2019-09/schema"
    || JSON.stringify(schema.oneOf) !== JSON.stringify(reports.map(([name]) => ({ $ref: `#/$defs/${name}` })))) {
  throw new Error("Unsupported report schema root");
}
function type(node) {
  if (node.$ref) {
    only(node, ["$ref"]);
    const name = node.$ref.replace(/^#\/\$defs\//, "");
    if (node.$ref !== `#/$defs/${name}` || !definitions[name]) throw new Error(`Unknown ref: ${node.$ref}`);
    return name;
  }
  if ("const" in node || "enum" in node) {
    only(node, "const" in node ? ["const"] : ["enum"]);
    const values = "const" in node ? [node.const] : node.enum;
    if (!values.length || values.some((value) => !["string", "number", "boolean"].includes(typeof value))) {
      throw new Error("Unsupported literal type");
    }
    return values.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (["string", "number", "integer", "boolean"].includes(node.type)) {
    only(node, ["type"]);
    return node.type === "integer" ? "number" : node.type;
  }
  if (node.type === "array") {
    only(node, ["type", "items"]);
    const item = type(node.items);
    return `readonly ${item.includes(" | ") ? `(${item})` : item}[]`;
  }
  if (node.type === "object" && node.additionalProperties && typeof node.additionalProperties === "object") {
    only(node, ["type", "additionalProperties"]);
    return `Readonly<Record<string, ${type(node.additionalProperties)}>>`;
  }
  throw new Error(`Unsupported report schema: ${JSON.stringify(node)}`);
}
const banner = `// Generated by scripts/generate-report-contract.mjs from astra-tools ${source.revision}.\n// Do not edit; use --check to detect drift.\n\n`;
const constants = reports.map(([name, constant]) =>
  `export const ${constant} = ${JSON.stringify(definitions[name].properties.schema_version.const)} as const;`).join("\n");
const interfaces = Object.entries(definitions).map(([name, node]) => {
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Unsupported type name: ${name}`);
  only(node, ["type", "properties", "required"]);
  if (node.type !== "object") throw new Error(`Expected a report object: ${name}`);
  const fields = Object.entries(node.properties).map(([key, property]) =>
    `  readonly ${/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : JSON.stringify(key)}${node.required.includes(key) ? "" : "?"}: ${type(property)};`);
  return `export interface ${name} {\n${fields.join("\n")}\n  readonly [key: string]: unknown;\n}`;
}).join("\n\n");
const outputs = {
  "src/reports/types.ts": `${banner}${constants}\n\n${interfaces}\n\nexport type Report = ResolvedAnalysis | ValidationReport | StatusReport;\n`,
  "src/reports/schema.ts": `${banner}export const reportSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`,
};
for (const [path, content] of Object.entries(outputs)) {
  const destination = resolve(root, path);
  if (check) {
    if (readFileSync(destination, "utf8") !== content) throw new Error(`Generated contract is stale: ${path}`);
  } else write(destination, content);
}
