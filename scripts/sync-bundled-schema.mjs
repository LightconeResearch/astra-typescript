import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const version = process.argv[2] ?? '0.0.14';
const url = `https://astra-spec.org/${version}/schema/astra.schema.json`;
const response = await fetch(url);

if (!response.ok) {
  throw new Error(`Could not download ${url}: HTTP ${response.status}`);
}

const schema = await response.json();
if (!schema || typeof schema !== 'object' || schema.version !== version) {
  throw new Error(
    `Expected ASTRA schema ${version}, received ${JSON.stringify(schema?.version)}`,
  );
}

const output = `// Generated by scripts/sync-bundled-schema.mjs from ${url}.
// Do not edit this file by hand.

export const BUNDLED_ASTRA_SPEC_VERSION = ${JSON.stringify(version)} as const;

export const bundledAstraSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};
`;

await writeFile(resolve('src/schema/bundled.ts'), output, 'utf8');
